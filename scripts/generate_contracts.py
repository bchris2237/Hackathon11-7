"""Generate contracts/models.py and contracts/models.ts from the JSON Schemas.

The three source schemas (scenario, result, api) reference each other by file.
Code generators want one self-contained document, so this script first bundles
them in memory into a single schema (renaming the one colliding $def), then runs:

  * datamodel-code-generator  -> contracts/models.py   (Pydantic 2)
  * frontend/scripts/gen-types.mjs (json-schema-to-typescript) -> contracts/models.ts

Usage (from the repository root, with the venv active and Node on PATH):

  python scripts/generate_contracts.py          # regenerate both files
  python scripts/generate_contracts.py --check  # exit 1 if either file is stale

Owner: Developer 2 (shared contracts). Edit the *.schema.json files, never the
generated models.
"""

from __future__ import annotations

import argparse
import copy
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTRACTS = ROOT / "contracts"
FRONTEND = ROOT / "frontend"

PY_HEADER = (
    "# GENERATED by scripts/generate_contracts.py from contracts/*.schema.json.\n"
    "# DO NOT EDIT BY HAND. Change the schemas, then regenerate.\n"
)


def _load(name: str) -> dict:
    return json.loads((CONTRACTS / name).read_text(encoding="utf-8"))


def _rewrite_refs(node, mapping):
    """Return a copy of node with every $ref passed through mapping."""
    if isinstance(node, dict):
        out = {}
        for key, value in node.items():
            if key == "$ref" and isinstance(value, str):
                out[key] = mapping(value)
            else:
                out[key] = _rewrite_refs(value, mapping)
        return out
    if isinstance(node, list):
        return [_rewrite_refs(item, mapping) for item in node]
    return node


def bundle() -> dict:
    """Merge scenario/result/api into one schema with only local #/$defs refs."""
    scenario = _load("scenario.schema.json")
    result = _load("result.schema.json")
    api = _load("api.schema.json")

    def scenario_ref(ref: str) -> str:
        return ref  # already local

    def result_ref(ref: str) -> str:
        # result.schema.json has its own Slug; it is renamed ResultSlug in the bundle.
        return "#/$defs/ResultSlug" if ref == "#/$defs/Slug" else ref

    def api_ref(ref: str) -> str:
        table = {
            "scenario.schema.json": "#/$defs/Scenario",
            "result.schema.json": "#/$defs/Result",
        }
        if ref in table:
            return table[ref]
        for prefix in ("scenario.schema.json#", "result.schema.json#"):
            if ref.startswith(prefix):
                return "#" + ref[len(prefix):]
        return ref

    defs: dict = {}

    def add(name: str, value: dict) -> None:
        if name in defs:
            raise SystemExit(f"Bundle name collision: {name}")
        defs[name] = value

    def split_root(schema: dict) -> tuple[dict, dict]:
        root = {k: v for k, v in schema.items() if k not in ("$schema", "$id", "$defs")}
        return root, schema.get("$defs", {})

    s_root, s_defs = split_root(scenario)
    add("Scenario", _rewrite_refs(s_root, scenario_ref))
    for name, value in s_defs.items():
        add(name, _rewrite_refs(value, scenario_ref))

    r_root, r_defs = split_root(result)
    add("Result", _rewrite_refs(r_root, result_ref))
    for name, value in r_defs.items():
        add("ResultSlug" if name == "Slug" else name, _rewrite_refs(value, result_ref))

    for name, value in api["$defs"].items():
        add(name, _rewrite_refs(value, api_ref))

    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "TradeMindContract",
        "$defs": copy.deepcopy(defs),
    }


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def generate_python(bundle_path: Path, out_path: Path) -> None:
    header_file = out_path.parent / "py_header.txt"
    header_file.write_text(PY_HEADER, encoding="utf-8", newline="\n")
    cmd = [
        sys.executable, "-m", "datamodel_code_generator",
        "--input", str(bundle_path),
        "--input-file-type", "jsonschema",
        "--output", str(out_path),
        "--output-model-type", "pydantic_v2.BaseModel",
        "--target-python-version", "3.12",
        "--disable-timestamp",
        "--use-title-as-name",
        "--enum-field-as-literal", "all",
        # Strict types: 600.0 or "600" must not be coerced into an integer minute.
        "--strict-types", "str", "int", "bool",
        "--use-annotated",
        "--use-standard-collections",
        "--use-union-operator",
        "--use-schema-description",
        "--custom-file-header-path", str(header_file),
        "--formatters", "black", "isort",
    ]
    subprocess.run(cmd, check=True, cwd=ROOT)
    out_path.write_text(_read(out_path), encoding="utf-8", newline="\n")


def generate_typescript(bundle_path: Path, out_path: Path) -> None:
    node = shutil.which("node")
    if node is None:
        raise SystemExit("Node.js is required to generate contracts/models.ts but was not found on PATH.")
    script = FRONTEND / "scripts" / "gen-types.mjs"
    if not (FRONTEND / "node_modules").exists():
        raise SystemExit("Run `npm --prefix frontend ci` first (json-schema-to-typescript is a frontend devDependency).")
    subprocess.run([node, str(script), str(bundle_path), str(out_path)], check=True, cwd=FRONTEND)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if generated files differ from committed ones")
    args = parser.parse_args()

    with tempfile.TemporaryDirectory() as tmp:
        tmpdir = Path(tmp)
        bundle_path = tmpdir / "bundle.schema.json"
        bundle_path.write_text(json.dumps(bundle(), indent=2) + "\n", encoding="utf-8", newline="\n")

        py_out = tmpdir / "models.py"
        ts_out = tmpdir / "models.ts"
        generate_python(bundle_path, py_out)
        generate_typescript(bundle_path, ts_out)

        targets = {CONTRACTS / "models.py": py_out, CONTRACTS / "models.ts": ts_out}
        if args.check:
            stale = [
                dest.name for dest, fresh in targets.items()
                if not dest.exists() or _read(dest) != _read(fresh)
            ]
            if stale:
                print(f"STALE generated contract files: {', '.join(stale)}. Run python scripts/generate_contracts.py")
                return 1
            print("Generated contract files are up to date: models.py, models.ts")
            return 0

        for dest, fresh in targets.items():
            dest.write_text(_read(fresh), encoding="utf-8", newline="\n")
            print(f"wrote {dest.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
